package com.example.util

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import com.example.model.TransactionItem
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ExportHelper {

  fun generateCsvContent(items: List<TransactionItem>): String {
    val sb = StringBuilder()
    // CSV Header matching forensic script
    sb.append("RRN,Waktu,ID_Kasir,User_ID_Konsumen,Nominal,Flag_Jam_Tutup,Flag_Split_Tx,Flag_Nominal_Bulat,Flag_Self_Tx,Flag_Benford_Anomali,Total_Fraud_Score,Kesimpulan_Audit\n")

    for (item in items) {
      val flagJam = if (item.flagJamTutup) 1 else 0
      val flagSplit = if (item.flagSplitTx) 1 else 0
      val flagBulat = if (item.flagNominalBulat) 1 else 0
      val flagSelf = if (item.flagSelfTx) 1 else 0
      val flagBenford = if (item.flagBenfordAnomali) 1 else 0

      sb.append("${item.rrn},")
      sb.append("${item.timeFormatted},")
      sb.append("${item.cashierId},")
      sb.append("${item.customerId},")
      sb.append("${item.amount},")
      sb.append("$flagJam,")
      sb.append("$flagSplit,")
      sb.append("$flagBulat,")
      sb.append("$flagSelf,")
      sb.append("$flagBenford,")
      sb.append("${item.totalFraudScore},")
      sb.append("\"${item.conclusionText}\"\n")
    }
    return sb.toString()
  }

  fun shareCsvFile(context: Context, items: List<TransactionItem>) {
    try {
      val csvData = generateCsvContent(items)
      val fileName = "hasil_audit_forensik_qris_${System.currentTimeMillis()}.csv"
      val file = File(context.cacheDir, fileName)
      file.writeText(csvData)

      val uri = FileProvider.getUriForFile(
        context,
        "${context.packageName}.fileprovider",
        file
      )

      val sendIntent = Intent(Intent.ACTION_SEND).apply {
        type = "text/csv"
        putExtra(Intent.EXTRA_STREAM, uri)
        putExtra(Intent.EXTRA_SUBJECT, "Laporan Audit Forensik QRIS - Audita")
        putExtra(Intent.EXTRA_TEXT, "Terlampir file CSV hasil analisis forensik digital transaksi QRIS.")
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
      }

      val chooser = Intent.createChooser(sendIntent, "Ekspor Laporan Audit (CSV)")
      chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      context.startActivity(chooser)
    } catch (e: Exception) {
      e.printStackTrace()
      // Fallback share as plain text if file writing had any issue
      val plainIntent = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        putExtra(Intent.EXTRA_SUBJECT, "Laporan Audit Forensik QRIS")
        putExtra(Intent.EXTRA_TEXT, generateCsvContent(items))
      }
      val chooser = Intent.createChooser(plainIntent, "Ekspor CSV")
      chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      context.startActivity(chooser)
    }
  }

  fun generateFormattedSummaryReport(items: List<TransactionItem>, isIndonesian: Boolean): String {
    val totalTx = items.size
    val totalAmount = items.sumOf { it.amount }
    val highRiskCount = items.count { it.totalFraudScore >= 2 }
    val lowRiskCount = items.count { it.totalFraudScore == 1 }
    val safeCount = items.count { it.totalFraudScore == 0 }

    val dateStr = SimpleDateFormat("dd MMMM yyyy HH:mm", Locale.getDefault()).format(Date())

    val sb = StringBuilder()
    sb.append("═══════════════════════════════════════════\n")
    sb.append("   AUDITA - LAPORAN EKSEKUTIF AUDIT QRIS   \n")
    sb.append("═══════════════════════════════════════════\n")
    sb.append("Tanggal Dokumen : $dateStr\n")
    sb.append("Sistem Enkripsi : AES-256 GCM Cloud-Backed\n")
    sb.append("Total Transaksi : $totalTx\n")
    sb.append("Total Nominal   : Rp %,d\n".format(totalAmount))
    sb.append("Risiko Tinggi   : $highRiskCount (${if (totalTx > 0) highRiskCount * 100 / totalTx else 0}%)\n")
    sb.append("Risiko Rendah   : $lowRiskCount\n")
    sb.append("Aman / Valid    : $safeCount\n")
    sb.append("───────────────────────────────────────────\n")
    sb.append("RINCIAN TEMUAN UTAMA:\n")

    val flagged = items.filter { it.totalFraudScore > 0 }
    if (flagged.isEmpty()) {
      sb.append("Semua transaksi dalam kondisi aman dan valid.\n")
    } else {
      for (f in flagged) {
        sb.append("• [${f.rrn}] Kasir: ${f.cashierId} | User: ${f.customerId}\n")
        sb.append("  Nominal: Rp %,d | Skor: ${f.totalFraudScore}\n".format(f.amount))
        val active = f.activeFlags.joinToString(", ") { it.getLabel(isIndonesian) }
        sb.append("  Indikator: $active\n")
        sb.append("  Status: ${f.conclusionText}\n\n")
      }
    }
    sb.append("═══════════════════════════════════════════\n")
    sb.append("Generated by Audita Mobile Forensic Engine\n")
    return sb.toString()
  }

  fun sharePdfSummaryReport(context: Context, items: List<TransactionItem>, isIndonesian: Boolean) {
    val report = generateFormattedSummaryReport(items, isIndonesian)
    try {
      val fileName = "Laporan_Forensik_Audita_${System.currentTimeMillis()}.txt"
      val file = File(context.cacheDir, fileName)
      file.writeText(report)

      val uri = FileProvider.getUriForFile(
        context,
        "${context.packageName}.fileprovider",
        file
      )

      val sendIntent = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        putExtra(Intent.EXTRA_STREAM, uri)
        putExtra(Intent.EXTRA_SUBJECT, "Laporan Audit Forensik Transaksi QRIS")
        putExtra(Intent.EXTRA_TEXT, report)
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
      }
      val chooser = Intent.createChooser(sendIntent, "Bagikan Laporan Audit")
      chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      context.startActivity(chooser)
    } catch (_: Exception) {
      val sendIntent = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        putExtra(Intent.EXTRA_SUBJECT, "Laporan Audit Forensik Transaksi QRIS")
        putExtra(Intent.EXTRA_TEXT, report)
      }
      val chooser = Intent.createChooser(sendIntent, "Bagikan Laporan Audit")
      chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      context.startActivity(chooser)
    }
  }
}
